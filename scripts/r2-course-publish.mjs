import { AwsClient } from 'aws4fetch';
const keys=['R2_ENDPOINT','R2_BUCKET','R2_ACCESS_KEY_ID','R2_SECRET_ACCESS_KEY'];
for(const key of keys) if(!process.env[key]) throw Error('Missing GitHub secret: '+key);
const client=new AwsClient({accessKeyId:process.env.R2_ACCESS_KEY_ID,secretAccessKey:process.env.R2_SECRET_ACCESS_KEY,service:'s3',region:'auto'});
const key='__pipeline-tests/'+(process.env.GITHUB_RUN_ID||'local')+'.json';
const base=process.env.R2_ENDPOINT.replace(/\/$/,'');
const url=base+'/'+encodeURIComponent(process.env.R2_BUCKET)+'/'+key.split('/').map(encodeURIComponent).join('/');
const body=JSON.stringify({test:'yqxyy-r2',time:new Date().toISOString()});
const res=await client.fetch(url,{method:'PUT',headers:{'content-type':'application/json'},body});
if(!res.ok) throw Error('R2 PUT failed: '+res.status+' '+(await res.text()).slice(0,200));
const check=await client.fetch(url,{method:'GET'});
if(!check.ok) throw Error('R2 GET failed: '+check.status);
if((await check.text())!==body) throw Error('R2 content mismatch');
console.log('PASS: R2 upload and download verified: '+key);
